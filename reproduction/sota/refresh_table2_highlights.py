"""Generate Table 2 presentation ranks from the unrounded published values."""
import csv
import hashlib
import json
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLES = ROOT / 'outputs/kbs/_main/_tables'
HIGHLIGHT_NOTE = (r'\textbf{Bold} and \underline{underlined} entries mark the highest and '
                  r'second-highest unrounded values per column among filled cells. ')


def ranking():
    with (TABLES / 'cells_results.csv').open(encoding='utf-8-sig', newline='') as stream:
        rows = list(csv.DictReader(stream))
    columns = {}
    for dataset in ('dbp', 'epkg', 'dwy', 'wk3l'):
        for metric in ('mrr', 'h1', 'h10'):
            entries = [r for r in rows if r['cell_id'].startswith(f'T2.{dataset}.')
                       and r['cell_id'].endswith('.' + metric) and r['value']]
            values = {r['cell_id']: Decimal(r['value']) for r in entries}
            assert all(v.is_finite() and 0 <= v <= 1 for v in values.values())
            ordered = sorted(set(values.values()), reverse=True)
            assert len(ordered) >= 2, (dataset, metric)
            columns[f'{dataset}.{metric}'] = {
                'best': sorted(k for k, v in values.items() if v == ordered[0]),
                'second': sorted(k for k, v in values.items() if v == ordered[1]),
                'unrounded_values': {r['cell_id']: r['value'] for r in entries},
            }
    return columns


def refresh_highlights():
    columns = ranking()
    lines = ['% Generated by reproduction/sota/refresh_table2_highlights.py.',
             '% Rank unrounded values; exclude pending cells; equal values share a rank.']
    for column in columns.values():
        for rank, command in (('best', r'\BestResult'), ('second', r'\SecondResult')):
            for cell in column[rank]:
                lines.append(r'\SetResultStyle{' + cell + '}{' + command + '}')
    (TABLES / 'table2_highlights.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    report = {
        'scope': 'Table 2; filled results only; all metrics higher is better',
        'ranking': 'stored unrounded values; ties share rank; second distinct value is second-best',
        'csv_sha256': hashlib.sha256((TABLES / 'cells_results.csv').read_bytes()).hexdigest(),
        'columns': columns,
    }
    (TABLES / 'table2_highlights.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    return report


if __name__ == '__main__':
    report = refresh_highlights()
    print(json.dumps({key: {rank: value[rank] for rank in ('best', 'second')}
                      for key, value in report['columns'].items()}))
